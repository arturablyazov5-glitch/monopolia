// Вопросы и ветки макета Figma «Продажа — квиз», 2035:5647.
type Step = { question: string; options?: string[]; multiple?: boolean; other?: boolean };
const land = ['До 6 соток', '6‑10 соток', '10‑15 соток', 'Больше 15 соток'];
const characteristics: Record<string, Step> = {
  'Квартира': { question: 'Сколько комнат в квартире?', options: ['Студия', '1', '2', '3', '4 и больше'] },
  'Дом': { question: 'Какая площадь дома?', options: ['До 60 м²', '60‑100 м²', '100‑150 м²', 'Больше 150 м²'] },
  'Участок': { question: 'Какая площадь участка?', options: land },
  'Гараж': { question: 'Какой у вас гараж?', options: ['Кирпичный или блочный', 'Металлический', 'Машиноместо в паркинге'] },
};
const generalArea: Step = { question: 'Какая площадь объекта?', options: ['До 50 м²', '50‑100 м²', '100‑300 м²', 'Больше 300 м²', 'Затрудняюсь ответить'] };
const condition: Record<string, Step> = {
  'Квартира': { question: 'В каком состоянии жилье?', options: ['Новое, без ремонта', 'Свежий ремонт', 'Старый ремонт', 'Требует ремонта'] },
  'Участок': { question: 'Что есть на участке? (можно выбрать несколько)', options: ['Электричество', 'Вода', 'Газ', 'Постройки', 'Подъезд по асфальту', 'Ничего'], multiple: true },
  'Гараж': { question: 'Что есть в гараже? (можно выбрать несколько)', options: ['Отопление', 'Охрана', 'Подвал', 'Розетка 380', 'Смотровая яма', 'Ничего'], multiple: true },
  'Коммерческая недвижимость': { question: 'Как помещение используется сейчас?', options: ['Сдается арендатору', 'Под свой бизнес', 'Пустует', 'Идет ремонт'] },
  'Другое': { question: 'Расскажите кратко об объекте', other: true },
};
export function sellQuizStep(type: string, step: number): Step {
  if (step === 2) return characteristics[type] || generalArea;
  if (step === 3) return condition[type === 'Дом' ? 'Квартира' : type] || condition['Другое'];
  return { question: 'Когда хотите продать?', options: ['Срочно, в течение месяца', 'За 2‑3 месяца', 'До полугода', 'Не тороплюсь'] };
}
